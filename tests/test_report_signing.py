def test_first_run_generates_a_key_at_the_documented_path(tmp_path) -> None:
    key = load_or_create_instance_key(tmp_path)
    assert key.generated_this_run is True
    assert (tmp_path / ".relian" / "instance-ed25519.pem").is_file()
    assert key.path.endswith("instance-ed25519.pem")


def test_the_generated_key_is_mode_0600(tmp_path) -> None:
    load_or_create_instance_key(tmp_path)
    mode = stat.S_IMODE((tmp_path / ".relian" / "instance-ed25519.pem").stat().st_mode)
    assert mode == 0o600, f"instance key is mode {mode:04o}"


def test_the_second_run_loads_the_same_key_and_says_so(tmp_path) -> None:
    first = load_or_create_instance_key(tmp_path)
    second = load_or_create_instance_key(tmp_path)
    assert second.generated_this_run is False
    assert second.fingerprint == first.fingerprint
    # Same recorded creation time on both runs — otherwise a per-run fact
    # would leak into the signed manifest and two runs would disagree for a
    # reason that has nothing to do with the tree.
    assert second.created_at == first.created_at


def test_the_generation_event_is_recorded_in_the_manifest_block(tmp_path) -> None:
    """The WP-2.1 asymmetry: generation is acceptable BECAUSE it is disclosed."""
    key = load_or_create_instance_key(tmp_path)
    record = key.record()
    assert record["generated_this_run"] is True
    assert record["fingerprint"] == key.fingerprint
    assert record["created_at"] == key.created_at
    assert "generated by Relian on first use" in record["origin"]
    assert "never held by Visionblox" in record["origin"]


def test_a_world_readable_key_is_refused_rather_than_used(tmp_path) -> None:
    load_or_create_instance_key(tmp_path)
    key_path = tmp_path / ".relian" / "instance-ed25519.pem"
    os.chmod(key_path, 0o644)
    with pytest.raises(SigningError, match="readable by someone other than its owner"):
        load_or_create_instance_key(tmp_path)


def test_a_corrupt_key_is_refused_and_never_silently_replaced(tmp_path) -> None:
    """Replacing an unreadable key would change the fingerprint under which
    every previous report was signed, without saying so."""
    load_or_create_instance_key(tmp_path)
    key_path = tmp_path / ".relian" / "instance-ed25519.pem"
    original = key_path.read_bytes()
    key_path.write_bytes(b"-----BEGIN PRIVATE KEY-----\nnot a key\n")
    os.chmod(key_path, 0o600)
    with pytest.raises(SigningError, match="could not be loaded"):
        load_or_create_instance_key(tmp_path)
    assert key_path.read_bytes() != original, "the fixture did not corrupt anything"
    assert key_path.read_bytes().startswith(b"-----BEGIN PRIVATE KEY-----\nnot a key")


def test_a_non_ed25519_key_is_refused(tmp_path) -> None:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import rsa

    (tmp_path / ".relian").mkdir()
    key_path = tmp_path / ".relian" / "instance-ed25519.pem"
    private = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    key_path.write_bytes(
        private.private_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PrivateFormat.PKCS8,
            encryption_algorithm=serialization.NoEncryption(),
        )
    )
    os.chmod(key_path, 0o600)
    with pytest.raises(SigningError, match="not an Ed25519 key"):
        load_or_create_instance_key(tmp_path)


def test_a_key_predating_the_creation_record_reports_unknown_not_a_guess(tmp_path) -> None:
    """R1 on a new surface: a creation time this installation cannot know is
    stated as unknown, never fabricated from the file's mtime."""
    load_or_create_instance_key(tmp_path)
    (tmp_path / ".relian" / "instance-key.json").unlink()
    key = load_or_create_instance_key(tmp_path)
    assert key.created_at.startswith("unknown")


def test_key_generation_failure_is_a_hard_stop(tmp_path) -> None:
    """Planted-red for acceptance ④'s sibling: no key, no report."""
    blocked = tmp_path / "blocked"
    blocked.write_text("this is a file, so .relian cannot be a directory under it")
    with pytest.raises(SigningError, match="Relian emits NO report"):
        load_or_create_instance_key(blocked)


