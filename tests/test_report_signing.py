def test_the_cli_writes_nothing_when_a_key_cannot_be_obtained(tmp_path) -> None:
    """Acceptance: the failure path is proven by planted-red, not asserted in
    prose. An unsigned artifact that looks signed is worse than no artifact."""
    home = tmp_path / "home"
    home.write_text("not a directory")
    out = tmp_path / "out"
    proc = subprocess.run(
        [sys.executable, "-m", "src.discovery.cli", "report", "build", str(DEMO),
         "--out", str(out), "--customer", "C", "--engagement", "E",
         "--contract-vehicle", "V", "--home", str(home)],
        cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=300,
    )
    assert proc.returncode == 2, proc.stdout + proc.stderr
    assert "REFUSED" in proc.stderr
    assert "No report was written" in proc.stderr
    assert not out.exists(), "a report directory was created despite the refusal"


def test_the_cli_emits_all_three_artifacts_and_names_the_unattested_state(tmp_path) -> None:
    out, _home = _run_build(tmp_path)
    assert (out / "report.json").is_file()
    assert (out / "report.md").is_file()
    assert (out / "report.manifest.json").is_file()


def _run_build(tmp_path, root: Path = DEMO, extra=()):
    home = tmp_path / "home"
    home.mkdir(exist_ok=True)
    out = tmp_path / "out"
    proc = subprocess.run(
        [sys.executable, "-m", "src.discovery.cli", "report", "build", str(root),
         "--out", str(out), "--customer", "Test Agency",
         "--engagement", "Data Discovery", "--contract-vehicle", "TEST-001",
         "--root-label", "examples/demo", "--home", str(home), *extra],
        cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=300,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    return out, home


def test_the_cli_says_valid_and_unattested_before_any_countersignature(tmp_path) -> None:
    home = tmp_path / "home"
