@pytest.fixture()
def signed(tmp_path):
    from src.discovery.copybook import resolve
    from src.discovery.layout import compute

    key = load_or_create_instance_key(tmp_path)
    resolution = resolve(DEMO)
    layouts = [
        layout for layout in (compute(n, resolution) for n in sorted(resolution.records))
        if layout is not None
    ]
    report = Report.build(
        resolution, layouts,
        ReportMeta("C", "E", "V", "0.1.0-test", "examples/demo"),
        repo_root=REPO_ROOT,
        instance_fingerprint=key.fingerprint,
        instance_public_key_hex=key.public_key_hex,
    )
    manifest = build_manifest(
        report,
        files=[("report.json", report.to_canonical_json())],
        tool_digests=tool_digests(REPO_ROOT),
        input_digest_rows=input_digests(resolution.records),
        instance=key,
        relian_version="0.1.0-test",
        python_version="3.11.0",
    )
    return report, sign_manifest(manifest, key), key


def test_the_manifest_records_digests_of_inputs_and_never_their_content(signed) -> None:
    """R12. The manifest is what the crossing hash is derived from, so its
    contents must be digests rather than the customer's code."""
    _report, manifest, _key = signed
    assert manifest["input_digests"], "no input digest was recorded at all"
    for row in manifest["input_digests"]:
        assert set(row) == {"name", "path", "sha256"}
        assert len(row["sha256"]) == 64
    blob = manifest_bytes(manifest).decode("utf-8")
    for marker in ("PIC ", "IDENTIFICATION DIVISION", "WORKING-STORAGE"):
        assert marker not in blob, f"the manifest carries source text: {marker!r}"


def test_the_manifest_carries_the_one_timestamp_in_the_deliverable(signed) -> None:
    _report, manifest, _key = signed
    assert manifest["generated_at"].endswith("+00:00")


def test_the_manifest_hash_excludes_the_signature_block(signed) -> None:
    _report, manifest, _key = signed
    without = {k: v for k, v in manifest.items() if k != "signature"}
    assert manifest_hash(manifest) == manifest_hash(without)
    assert manifest["signature"]["manifest_sha256"] == manifest_hash(manifest)


def test_editing_the_manifest_changes_its_hash(signed) -> None:
    _report, manifest, _key = signed
    before = manifest_hash(manifest)
    tampered = json.loads(json.dumps(manifest))
    tampered["files"][0]["sha256"] = "0" * 64
    assert manifest_hash(tampered) != before


def test_the_instance_signature_verifies_over_the_manifest_hash(signed) -> None:
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

    _report, manifest, _key = signed
    block = manifest["signature"]
    Ed25519PublicKey.from_public_bytes(
        bytes.fromhex(block["public_key_hex"])
    ).verify(bytes.fromhex(block["signature_hex"]),
             block["manifest_sha256"].encode("utf-8"))


def test_the_manifest_names_the_signed_artifact_and_the_derived_ones(signed) -> None:
    _report, manifest, _key = signed
    assert manifest["signed_artifact"] == "report.json"
    assert manifest["derived_unsigned_artifacts"] == ["report.md"]


