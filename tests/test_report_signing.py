"""WP-2.3 §3.2/§3.3 — the instance key, the manifest, and ``countersign.py``.

The instance layer's whole justification is DISCLOSURE. ``bench/harness/
commit.py`` generates a signing key when the file is absent, and WP-2.1
recorded that as a defect: it produces a manifest that verifies perfectly under
a fingerprint nobody has ever seen. Generation here is intended — and what
makes it acceptable rather than the same defect is that the event reaches the
artifact. So the disclosure is asserted, not assumed:

* the report prints the fingerprint and states how the key came to exist;
* the manifest records the generation event, the path and the creation time;
* a run that cannot obtain a key writes NOTHING, and that is proven by
  planted-red rather than by reading the code.

``tools/countersign.py`` is exercised through its process entry point, because
that is the surface the operator uses. Its three refusals — absent key, a hash
that is not 64 hex characters, and the benchmark key (D23) — each get a test.
"""

